// Lists the sound folders into js/manifest.js (browsers can't list folders).
// Runs automatically before `npm run dist`; run `node tools/manifest.js` after adding files.
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const list = d => { try { return fs.readdirSync(path.join(root, d)).filter(f => /\.(mp3|ogg|wav|opus|m4a)$/i.test(f)).sort().map(f => d + '/' + f); } catch (e) { return []; } };
const m = {
  songs: list('assets/music/songs'),
  win: list('assets/music/win'),
  lose: list('assets/music/lose'),
  death: list('assets/sfx/death'),
};
fs.writeFileSync(path.join(root, 'js/manifest.js'), '// generated by tools/manifest.js\nconst MANIFEST = ' + JSON.stringify(m, null, 1) + ';\n');
console.log(Object.entries(m).map(([k, v]) => k + ': ' + v.length).join(', '));
